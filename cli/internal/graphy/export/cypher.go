package export

// Cypher output for Apache AGE (PostgreSQL).
//
// AGE does not consume a bare .cypher file: every statement travels inside a
// SQL `cypher('<graph>', $$ … $$) AS (v agtype)` call, so what this emits is a
// psql script. Three AGE constraints shape the mapping:
//
//   - A vertex carries exactly one label, unlike Neo4j's multi-label vertices.
//     The label is therefore the entity kind, and the kind is repeated as a
//     property so a query can filter without enumerating the label set.
//   - A label in a pattern must be a literal, so edges are grouped by relation
//     (and by which site properties they carry) and loaded per group.
//   - Endpoint lookup by id is a sequential scan until the id property is
//     indexed, so the indexes go in between the vertices and the edges.
//
// The script is a full snapshot: it clears the graph before loading so a
// re-export after a rebuild cannot strand vertices for code that no longer
// exists.

import (
	"fmt"
	"io"
	"sort"
	"strconv"
	"strings"

	"okfw/cli/internal/graphy/model"
)

const (
	// DefaultCypherGraph is the AGE graph name, which is also the PostgreSQL
	// schema AGE creates for it.
	DefaultCypherGraph = "graphy"
	// DefaultCypherBatch is how many CREATE clauses (or UNWIND rows) go into
	// one cypher() call. One statement per element would mean a parse and plan
	// per element; one statement for everything would build a single enormous
	// query plan.
	DefaultCypherBatch = 500
)

// CypherOptions configures the AGE emitter.
type CypherOptions struct {
	Generator  string
	GraphName  string // default DefaultCypherGraph; sanitized to a SQL identifier
	BatchSize  int    // default DefaultCypherBatch
	NoTruncate bool   // append into the existing graph instead of clearing it
}

// WriteCypher writes a psql script that loads the snapshot into Apache AGE.
//
// Like the other whole-graph writers it stamps no timestamp, so an unchanged
// graph re-exports byte for byte identically.
func WriteCypher(w io.Writer, g *Graph, opts CypherOptions) error {
	name := SanitizeGraphName(opts.GraphName)
	batch := opts.BatchSize
	if batch <= 0 {
		batch = DefaultCypherBatch
	}

	var stmts []cypherStmt
	if !opts.NoTruncate {
		stmts = append(stmts, cypherStmt{
			comment: "Full snapshot: clear the graph so a reload cannot leave stale vertices behind.",
			body:    "MATCH (n) DETACH DELETE n",
		})
	}
	vertices, labels := cypherVertices(g, batch)
	stmts = append(stmts, vertices...)
	edges := cypherEdges(g, batch)

	// The tag has to clear every body, including the edge statements written
	// after the index block, or a doc comment containing the tag would end the
	// dollar-quoted string early and leave the rest of the script as SQL.
	tag := dollarTag(append(append([]cypherStmt(nil), stmts...), edges...))

	b := &strings.Builder{}
	writeCypherHeader(b, g, opts, name)
	for _, s := range stmts {
		s.write(b, name, tag)
	}
	writeCypherIndexes(b, name, tag, labels)
	for _, s := range edges {
		s.write(b, name, tag)
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// cypherStmt is one cypher() call: a comment and the query it wraps.
type cypherStmt struct {
	comment string
	body    string
}

func (s cypherStmt) write(b *strings.Builder, graph, tag string) {
	if s.comment != "" {
		fmt.Fprintf(b, "-- %s\n", s.comment)
	}
	fmt.Fprintf(b, "SELECT * FROM cypher('%s', %s\n%s\n%s) AS (v agtype);\n\n", graph, tag, s.body, tag)
}

func writeCypherHeader(b *strings.Builder, g *Graph, opts CypherOptions, name string) {
	st := g.Stats()
	fmt.Fprintf(b, "-- graphy code graph of %s → Apache AGE (PostgreSQL)\n", g.Root)
	if opts.Generator != "" {
		fmt.Fprintf(b, "-- Generated by %s\n", opts.Generator)
	}
	fmt.Fprintf(b, "-- %d vertices, %d edges, %d communities, %d files\n--\n", st.Nodes, st.Edges, st.Communities, st.Files)
	b.WriteString("--   psql -d <database> -f <this file>\n--\n")
	b.WriteString("-- Each vertex carries one label — the entity kind — plus its graphy node\n")
	b.WriteString("-- id as the `id` property; edges are labelled with the relation. Query it as:\n--\n")
	fmt.Fprintf(b, "--   SELECT * FROM cypher('%s', $q$ MATCH (a:Function)-[:CALLS]->(b)\n", name)
	b.WriteString("--     RETURN a.label, b.label $q$) AS (caller agtype, callee agtype);\n")
	if opts.NoTruncate {
		b.WriteString("--\n-- Appending: this script does not clear the graph first, so loading it twice\n")
		b.WriteString("-- duplicates every vertex and edge.\n")
	}
	b.WriteString("\nLOAD 'age';\nSET search_path = ag_catalog, \"$user\", public;\n\n")
	b.WriteString("-- Create the graph on first load; do nothing on later ones.\n")
	fmt.Fprintf(b, "DO $do$\nBEGIN\n  IF NOT EXISTS (SELECT 1 FROM ag_catalog.ag_graph WHERE name = '%s') THEN\n", name)
	fmt.Fprintf(b, "    PERFORM ag_catalog.create_graph('%s');\n  END IF;\nEND\n$do$;\n\n", name)
}

// writeCypherIndexes indexes the id property of every label that was created.
//
// Index creation is an optimization, and AGE's property-index syntax is
// version-sensitive, so each one is attempted individually and a failure is
// reported and skipped rather than aborting the load — a slow graph beats a
// script that dies two thirds of the way through.
func writeCypherIndexes(b *strings.Builder, graph, tag string, labels []string) {
	if len(labels) == 0 {
		return
	}
	quoted := make([]string, len(labels))
	for i, l := range labels {
		quoted[i] = "'" + l + "'"
	}
	b.WriteString("-- Index each label's id before loading edges: every edge below looks its\n")
	b.WriteString("-- endpoints up by id, which is a sequential scan until this exists.\n")
	b.WriteString("DO $do$\nDECLARE\n  lbl text;\nBEGIN\n")
	fmt.Fprintf(b, "  FOREACH lbl IN ARRAY ARRAY[%s] LOOP\n", strings.Join(quoted, ", "))
	b.WriteString("    BEGIN\n      EXECUTE format(\n")
	b.WriteString("        'CREATE INDEX IF NOT EXISTS %I ON %I.%I USING btree " +
		"(ag_catalog.agtype_access_operator(VARIADIC ARRAY[properties, ''\"id\"''::agtype]))',\n")
	fmt.Fprintf(b, "        lbl || '_id_idx', '%s', lbl);\n", graph)
	b.WriteString("    EXCEPTION WHEN others THEN\n")
	b.WriteString("      RAISE NOTICE 'graphy: skipped id index on %: %', lbl, SQLERRM;\n")
	b.WriteString("    END;\n  END LOOP;\nEND\n$do$;\n\n")
}

// cypherVertices renders the CREATE batches and reports the labels used, in
// first-appearance-sorted order so the index block is deterministic too.
//
// Each vertex spells out its own property map rather than sharing one shape
// via UNWIND: property sets are ragged here (most nodes have no signature, few
// have a body) and a shared shape would have to pad the gaps with nulls.
func cypherVertices(g *Graph, batch int) ([]cypherStmt, []string) {
	used := map[string]bool{}
	var clauses []string
	for _, n := range g.Nodes {
		label := vertexLabel(n.Kind)
		used[label] = true

		var p cypherProps
		p.str("id", n.ID)
		p.str("label", n.Label)
		p.str("kind", string(n.Kind))
		p.str("language", n.Language)
		p.str("source_file", n.File)
		p.num("start_line", n.Span.StartLine)
		p.num("end_line", n.Span.EndLine)
		p.str("signature", n.Signature)
		p.str("doc", n.Doc)
		p.str("body", n.Body)
		if id, cl, ok := g.Community(n.ID); ok {
			p.exact("community", id)
			p.str("community_label", cl)
		}
		p.num("degree", n.Degree)
		p.yes("external", n.External)
		clauses = append(clauses, fmt.Sprintf("CREATE (:%s %s)", label, p))
	}

	labels := make([]string, 0, len(used))
	for l := range used {
		labels = append(labels, l)
	}
	sort.Strings(labels)

	var stmts []cypherStmt
	for i, chunk := range chunked(clauses, batch) {
		s := cypherStmt{body: strings.Join(chunk, "\n")}
		if i == 0 {
			s.comment = fmt.Sprintf("Vertices: %d across %d labels.", len(clauses), len(labels))
		}
		stmts = append(stmts, s)
	}
	return stmts, labels
}

// edgeShape groups edges that can share one statement: same relation (the
// label must be a literal) and the same site properties (so no row in the
// batch needs a null).
type edgeShape struct {
	relation model.Relation
	hasFile  bool
	hasLine  bool
}

func (s edgeShape) less(o edgeShape) bool {
	if s.relation != o.relation {
		return s.relation < o.relation
	}
	if s.hasFile != o.hasFile {
		return !s.hasFile
	}
	return !s.hasLine && o.hasLine
}

// cypherEdges renders one UNWIND batch per shape. Endpoints are matched by id
// rather than created, so a stale reference in the graph fails loudly as a
// missing row instead of quietly inventing an empty vertex.
func cypherEdges(g *Graph, batch int) []cypherStmt {
	rows := map[edgeShape][]string{}
	var shapes []edgeShape
	for _, e := range g.Edges {
		sh := edgeShape{relation: e.Relation, hasFile: e.File != "", hasLine: e.Line != 0}
		if _, seen := rows[sh]; !seen {
			shapes = append(shapes, sh)
		}
		var p cypherProps
		p.str("s", e.Source)
		p.str("t", e.Target)
		p.str("c", string(e.Confidence))
		if sh.hasFile {
			p.str("f", e.File)
		}
		if sh.hasLine {
			p.exact("l", e.Line)
		}
		rows[sh] = append(rows[sh], "  "+p.String())
	}
	sort.Slice(shapes, func(i, j int) bool { return shapes[i].less(shapes[j]) })

	var stmts []cypherStmt
	for _, sh := range shapes {
		var props cypherProps
		props.ref("confidence", "r.c")
		if sh.hasFile {
			props.ref("site_file", "r.f")
		}
		if sh.hasLine {
			props.ref("site_line", "r.l")
		}
		for i, chunk := range chunked(rows[sh], batch) {
			body := fmt.Sprintf("UNWIND [\n%s\n] AS r\nMATCH (a) WHERE a.id = r.s\nMATCH (b) WHERE b.id = r.t\n"+
				"CREATE (a)-[:%s %s]->(b)", strings.Join(chunk, ",\n"), relationLabel(sh.relation), props)
			s := cypherStmt{body: body}
			if i == 0 {
				s.comment = fmt.Sprintf("%s edges: %d.", relationLabel(sh.relation), len(rows[sh]))
			}
			stmts = append(stmts, s)
		}
	}
	return stmts
}

// cypherProps builds a Cypher map literal, dropping absent values so no
// property is stored as null.
type cypherProps struct{ parts []string }

func (p *cypherProps) add(key, value string) { p.parts = append(p.parts, key+": "+value) }

func (p *cypherProps) str(key, v string) {
	if v != "" {
		p.add(key, cypherString(v))
	}
}

func (p *cypherProps) num(key string, v int) {
	if v != 0 {
		p.add(key, strconv.Itoa(v))
	}
}

// exact emits a number that is meaningful at zero (a community id, a line).
func (p *cypherProps) exact(key string, v int) { p.add(key, strconv.Itoa(v)) }

func (p *cypherProps) yes(key string, v bool) {
	if v {
		p.add(key, "true")
	}
}

// ref emits an unquoted expression, for property values read off an UNWIND row.
func (p *cypherProps) ref(key, expr string) { p.add(key, expr) }

func (p cypherProps) String() string { return "{" + strings.Join(p.parts, ", ") + "}" }

// cypherString renders a single-quoted Cypher string literal.
//
// Control characters other than the three with escapes are dropped rather than
// escaped: they carry no meaning in a doc comment or a signature, and AGE's
// lexer would have to be trusted to handle each one.
func cypherString(s string) string {
	var b strings.Builder
	b.Grow(len(s) + 2)
	b.WriteByte('\'')
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '\'':
			b.WriteString(`\'`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if r < 0x20 || r == 0x7f {
				continue
			}
			b.WriteRune(r)
		}
	}
	b.WriteByte('\'')
	return b.String()
}

// dollarTag picks a PostgreSQL dollar-quote tag that appears in no statement
// body. Cypher strings are escaped for Cypher, not for SQL, so a doc comment
// containing the tag would otherwise close the quote and spill the rest of the
// query into the surrounding SQL.
func dollarTag(stmts []cypherStmt) string {
	for i := 0; ; i++ {
		tag := "$graphy$"
		if i > 0 {
			tag = fmt.Sprintf("$graphy%d$", i)
		}
		clear := true
		for _, s := range stmts {
			if strings.Contains(s.body, tag) {
				clear = false
				break
			}
		}
		if clear {
			return tag
		}
	}
}

// vertexLabel maps an entity kind to an AGE vertex label.
func vertexLabel(k model.Kind) string {
	label := camelCase(string(k))
	if label == "" {
		return "Node"
	}
	return label
}

// relationLabel maps a relation to an AGE edge label in the SCREAMING_SNAKE
// convention Cypher uses for relationship types.
func relationLabel(r model.Relation) string {
	var b strings.Builder
	for _, ch := range strings.ToUpper(string(r)) {
		if (ch >= 'A' && ch <= 'Z') || (ch >= '0' && ch <= '9') {
			b.WriteRune(ch)
		} else {
			b.WriteByte('_')
		}
	}
	if b.Len() == 0 {
		return "RELATED"
	}
	return leadingLetter(b.String(), "R_")
}

// camelCase joins the alphanumeric runs of s with each one capitalized.
func camelCase(s string) string {
	var b strings.Builder
	upper := true
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z':
			if upper {
				r -= 'a' - 'A'
			}
			b.WriteRune(r)
			upper = false
		case (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9'):
			b.WriteRune(r)
			upper = false
		default:
			upper = true
		}
	}
	if b.Len() == 0 {
		return ""
	}
	return leadingLetter(b.String(), "N")
}

// leadingLetter prefixes s when it would otherwise start with a digit, which
// no SQL identifier may do.
func leadingLetter(s, prefix string) string {
	if s[0] >= '0' && s[0] <= '9' {
		return prefix + s
	}
	return s
}

// SanitizeGraphName turns a requested graph name into one usable as both an
// AGE graph and the PostgreSQL schema it creates: lowercase, alphanumeric and
// underscores, no leading digit, within the 63-byte identifier limit.
func SanitizeGraphName(name string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(strings.TrimSpace(name)) {
		switch {
		case (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '_':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	out := strings.Trim(b.String(), "_")
	if out == "" {
		return DefaultCypherGraph
	}
	out = leadingLetter(out, "g_")
	if len(out) > 63 {
		out = out[:63]
	}
	return out
}

// chunked splits a slice into runs of at most size.
func chunked[T any](items []T, size int) [][]T {
	var out [][]T
	for start := 0; start < len(items); start += size {
		end := min(start+size, len(items))
		out = append(out, items[start:end])
	}
	return out
}
