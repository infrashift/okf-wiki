func TestCypherIsDeterministic(t *testing.T) {
	first := renderCypher(t, formatFixture(), CypherOptions{GraphName: "myproj"})
	g := formatFixture()
	reversed := make([]model.Node, len(g.Nodes))
	for i, n := range g.Nodes {
		reversed[len(g.Nodes)-1-i] = n
	}
	shuffled := NewGraph(g.Root, reversed, g.Edges, []store.Community{g.Communities[1], g.Communities[0]}, g.Files)
	if second := renderCypher(t, shuffled, CypherOptions{GraphName: "myproj"}); first != second {
		t.Error("Cypher output depends on input order")
	}
}

