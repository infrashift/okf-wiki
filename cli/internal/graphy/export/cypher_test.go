func renderCypher(t *testing.T, g *Graph, opts CypherOptions) string {
	t.Helper()
	var buf bytes.Buffer
	if err := WriteCypher(&buf, g, opts); err != nil {
		t.Fatal(err)
	}
	return buf.String()
}

// cypherCall is one wrapped statement. AGE accepts Cypher only inside a
// cypher() call with a column definition list, so this is the shape every
// statement in the file has to have.
type cypherCall struct{ graph, tag, body string }

var cypherCallHead = regexp.MustCompile(`SELECT \* FROM cypher\('([a-z0-9_]+)', (\$graphy\d*\$)\n`)

// parseCypherCalls splits the script into its wrapped statements, failing the
// test on any call that is not closed by its own tag. RE2 has no
// backreferences, so the closing tag is matched by hand.
func parseCypherCalls(t *testing.T, out string) []cypherCall {
	t.Helper()
	var calls []cypherCall
	for _, m := range cypherCallHead.FindAllStringSubmatchIndex(out, -1) {
		c := cypherCall{graph: out[m[2]:m[3]], tag: out[m[4]:m[5]]}
		rest := out[m[1]:]
		end := strings.Index(rest, "\n"+c.tag+") AS (v agtype);")
		if end < 0 {
			t.Fatalf("cypher() call is not closed by %s: %.200s", c.tag, rest)
		}
		c.body = rest[:end]
		calls = append(calls, c)
	}
	return calls
}

func TestCypherScriptStructure(t *testing.T) {
	out := renderCypher(t, formatFixture(), CypherOptions{Generator: "graphy test", GraphName: "myproj"})

	for _, want := range []string{
		"LOAD 'age';",
		`SET search_path = ag_catalog, "$user", public;`,
		"IF NOT EXISTS (SELECT 1 FROM ag_catalog.ag_graph WHERE name = 'myproj') THEN",
		"PERFORM ag_catalog.create_graph('myproj');",
		"MATCH (n) DETACH DELETE n",
		"-- Generated by graphy test",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("script is missing %q", want)
		}
	}

	calls := parseCypherCalls(t, out)
	if len(calls) < 3 {
		t.Fatalf("found %d cypher() calls, want the truncate plus vertices plus edges", len(calls))
	}
	for _, c := range calls {
		if c.graph != "myproj" {
			t.Errorf("cypher() call against graph %q, want myproj", c.graph)
		}
	}
	// Nothing may sit outside a wrapped call or a comment: a bare Cypher line
	// is a syntax error to psql.
	outside := out
	for _, c := range calls {
		outside = strings.Replace(outside, c.body, "", 1)
	}
	for _, line := range strings.Split(outside, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "--") {
			continue
		}
		if strings.HasPrefix(line, "CREATE (") || strings.HasPrefix(line, "MATCH ") || strings.HasPrefix(line, "UNWIND ") {
			t.Errorf("Cypher outside a cypher() call: %q", line)
		}
	}
}

func TestCypherVerticesAndEdges(t *testing.T) {
	out := renderCypher(t, formatFixture(), CypherOptions{GraphName: "myproj"})

	// One label per vertex — AGE has no multi-label vertices — and the kind is
	// kept as a property too.
	for _, want := range []string{
		`CREATE (:Function {id: 'go:function:a.go#Run', label: 'Run', kind: 'function', language: 'go', ` +
			`source_file: 'a.go', start_line: 10, end_line: 20, signature: 'func Run() error', ` +
			`doc: 'Run starts it.', community: 0, community_label: 'core', degree: 3})`,
		`CREATE (:External {id: 'go:external:#net/http', label: 'net/http', kind: 'external', ` +
			`language: 'go', degree: 1, external: true})`,
		`CREATE (:Rationale {`,
	} {
		if !strings.Contains(out, want) {
			t.Errorf("missing vertex clause:\n%s", want)
		}
	}
	// The unclustered node must not be handed community 0.
	if strings.Contains(out, `id: 'go:external:#net/http', label: 'net/http', kind: 'external', language: 'go', community:`) {
		t.Error("an unclustered node was given a community")
	}

	for _, want := range []string{
		"CREATE (a)-[:CALLS {confidence: r.c, site_file: r.f, site_line: r.l}]->(b)",
		"CREATE (a)-[:IMPORTS {confidence: r.c}]->(b)",
		"CREATE (a)-[:EXPLAINS {confidence: r.c, site_file: r.f, site_line: r.l}]->(b)",
		"MATCH (a) WHERE a.id = r.s",
		"MATCH (b) WHERE b.id = r.t",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("missing edge construct: %q", want)
		}
	}
}

// TestCypherEdgeShapesCarryNoNulls: edges are grouped so every row in an UNWIND
// batch has the same keys. Mixing an edge that has a call site with one that
// does not would force null padding, and AGE stores that null as a property.
func TestCypherEdgeShapesCarryNoNulls(t *testing.T) {
	out := renderCypher(t, formatFixture(), CypherOptions{GraphName: "myproj"})
	if strings.Contains(out, "null") {
		t.Error("a property was emitted as null")
	}
	// The site-less import must not be batched with the sited call.
	for _, stmt := range parseCypherCalls(t, out) {
		body := stmt.body
		if !strings.Contains(body, "UNWIND") {
			continue
		}
		hasSiteRows := strings.Contains(body, ", f: '")
		declaresSite := strings.Contains(body, "site_file: r.f")
		if hasSiteRows != declaresSite {
			t.Errorf("batch rows and property list disagree about the call site:\n%s", body)
		}
	}
}

// TestCypherEscapesStringLiterals: doc comments and signatures contain quotes,
// backslashes and newlines. AGE's Cypher lexer takes backslash escapes, and an
// unescaped quote would end the literal and corrupt the rest of the statement.
func TestCypherEscapesStringLiterals(t *testing.T) {
	g := NewGraph("/repo", []model.Node{{
		ID: "go:function:a.go#F", Label: "F", Kind: model.KindFunction,
		Doc:       `it's a \backslash\ and` + "\nnewline\ttab",
		Signature: `func F(s string) // "quoted"`,
		Body:      "drop\x00control\x08chars",
		Degree:    1,
	}}, nil, nil, 1)

	out := renderCypher(t, g, CypherOptions{GraphName: "myproj"})
	want := `doc: 'it\'s a \\backslash\\ and\nnewline\ttab'`
	if !strings.Contains(out, want) {
		t.Errorf("escaping is wrong; want %s in:\n%s", want, out)
	}
	if !strings.Contains(out, `signature: 'func F(s string) // "quoted"'`) {
		t.Error("double quotes need no escaping inside a single-quoted literal")
	}
	if !strings.Contains(out, `body: 'dropcontrolchars'`) {
		t.Error("control characters should be dropped, not passed through")
	}
	// A stray unescaped quote would show up as an odd number of them.
	if n := strings.Count(out, "'") - 2*strings.Count(out, `\'`); n%2 != 0 {
		t.Error("unbalanced single quotes — a literal is not closed")
	}
}

// TestCypherDollarTagAvoidsCollision: Cypher strings are escaped for Cypher,
// not for SQL. A doc comment containing the dollar-quote tag would otherwise
// close the quoted block early and spill the rest of the query into psql.
func TestCypherDollarTagAvoidsCollision(t *testing.T) {
	g := NewGraph("/repo", []model.Node{{
		ID: "go:function:a.go#F", Label: "F", Kind: model.KindFunction,
		Doc: "shell money: $graphy$ and $graphy1$", Degree: 1,
	}}, nil, nil, 1)

	out := renderCypher(t, g, CypherOptions{GraphName: "myproj"})
	calls := parseCypherCalls(t, out)
	if len(calls) == 0 {
		t.Fatalf("no well-formed cypher() call survived:\n%s", out)
	}
	tag := calls[0].tag
	if tag == "$graphy$" || tag == "$graphy1$" {
		t.Errorf("tag %s collides with content in the document", tag)
	}
	for _, c := range calls {
		if strings.Contains(c.body, tag) {
			t.Errorf("statement body contains its own closing tag %s", tag)
		}
	}
}

func TestCypherBatching(t *testing.T) {
	var nodes []model.Node
	for _, id := range []string{"a", "b", "c", "d", "e"} {
		nodes = append(nodes, model.Node{
			ID: "go:function:f.go#" + id, Label: id, Kind: model.KindFunction, Degree: 1,
		})
	}
	var edges []model.Edge
	for _, id := range []string{"b", "c", "d", "e"} {
		edges = append(edges, model.Edge{
			Source: "go:function:f.go#a", Target: "go:function:f.go#" + id,
			Relation: model.RelCalls, Confidence: model.ConfExtracted,
		})
	}
	out := renderCypher(t, NewGraph("/repo", nodes, edges, nil, 1),
		CypherOptions{GraphName: "myproj", BatchSize: 2})

	var vertexStmts, edgeStmts int
	for _, c := range parseCypherCalls(t, out) {
		switch {
		case strings.Contains(c.body, "UNWIND"):
			edgeStmts++
		case strings.Contains(c.body, "CREATE (:"):
			vertexStmts++
		}
	}
	if vertexStmts != 3 { // 5 vertices, 2 per statement
		t.Errorf("got %d vertex statements, want 3", vertexStmts)
	}
	if edgeStmts != 2 { // 4 edges, 2 per statement
		t.Errorf("got %d edge statements, want 2", edgeStmts)
	}
}

// TestCypherIndexesEveryEmittedLabel: the edge statements look their endpoints
// up by id, so a label whose index is missing is a sequential scan per edge.
func TestCypherIndexesEveryEmittedLabel(t *testing.T) {
	out := renderCypher(t, formatFixture(), CypherOptions{GraphName: "myproj"})
	idx := strings.Index(out, "FOREACH lbl IN ARRAY ARRAY[")
	if idx < 0 {
		t.Fatal("no index block")
	}
	block := out[idx : strings.Index(out[idx:], "\n")+idx]
	for _, label := range []string{"External", "Function", "Rationale"} {
		if !strings.Contains(block, "'"+label+"'") {
			t.Errorf("label %s is created but never indexed: %s", label, block)
		}
	}
	// Indexes must exist before the edges that need them.
	if idx > strings.Index(out, "UNWIND") {
		t.Error("the index block comes after the edge statements")
	}
	// A failed index is an optimization lost, not a load aborted.
	if !strings.Contains(out, "EXCEPTION WHEN others THEN") {
		t.Error("index creation is not guarded")
	}
}

