package export

// GraphML output for the code graph — the interchange format Gephi, yEd,
// Cytoscape and networkx all read.
//
// GraphML declares its attribute vocabulary up front as <key> elements and
// then references those keys from each <data>. Readers use attr.type to decide
// how to parse a value, so a key declared "int" must never carry an empty
// string: absent values are omitted rather than emitted blank.

import (
	"encoding/xml"
	"fmt"
	"io"
	"strconv"
)

const (
	graphmlNS     = "http://graphml.graphdrawing.org/xmlns"
	graphmlXSI    = "http://www.w3.org/2001/XMLSchema-instance"
	graphmlSchema = graphmlNS + " http://graphml.graphdrawing.org/xmlns/1.0/graphml.xsd"
)

// graphmlKeys is the attribute vocabulary. The key id doubles as the attribute
// name, which is legal and much easier to read in the output than the
// conventional d0/d1/… — no node attribute shares a name with an edge one, so
// the ids stay unique across the document as GraphML requires.
var graphmlKeys = []graphmlKey{
	{ID: "label", For: "node", Name: "label", Type: "string"},
	{ID: "kind", For: "node", Name: "kind", Type: "string"},
	{ID: "language", For: "node", Name: "language", Type: "string"},
	{ID: "source_file", For: "node", Name: "source_file", Type: "string"},
	{ID: "start_line", For: "node", Name: "start_line", Type: "int"},
	{ID: "end_line", For: "node", Name: "end_line", Type: "int"},
	{ID: "signature", For: "node", Name: "signature", Type: "string"},
	{ID: "doc", For: "node", Name: "doc", Type: "string"},
	{ID: "body", For: "node", Name: "body", Type: "string"},
	{ID: "community", For: "node", Name: "community", Type: "int"},
	{ID: "community_label", For: "node", Name: "community_label", Type: "string"},
	{ID: "degree", For: "node", Name: "degree", Type: "int"},
	{ID: "external", For: "node", Name: "external", Type: "boolean"},
	{ID: "relation", For: "edge", Name: "relation", Type: "string"},
	{ID: "confidence", For: "edge", Name: "confidence", Type: "string"},
	{ID: "site_file", For: "edge", Name: "site_file", Type: "string"},
	{ID: "site_line", For: "edge", Name: "site_line", Type: "int"},
}

type graphmlDocument struct {
	XMLName        xml.Name `xml:"graphml"`
	NS             string   `xml:"xmlns,attr"`
	XSI            string   `xml:"xmlns:xsi,attr"`
	SchemaLocation string   `xml:"xsi:schemaLocation,attr"`
	Desc           string   `xml:"desc,omitempty"`
	// Order matters: the schema is (desc?, key*, graph*).
	Keys  []graphmlKey `xml:"key"`
	Graph graphmlGraph `xml:"graph"`
}

type graphmlKey struct {
	ID   string `xml:"id,attr"`
	For  string `xml:"for,attr"`
	Name string `xml:"attr.name,attr"`
	Type string `xml:"attr.type,attr"`
}

type graphmlGraph struct {
	ID          string        `xml:"id,attr"`
	EdgeDefault string        `xml:"edgedefault,attr"`
	Nodes       []graphmlNode `xml:"node"`
	Edges       []graphmlEdge `xml:"edge"`
}

type graphmlNode struct {
	ID   string        `xml:"id,attr"`
	Data []graphmlData `xml:"data"`
}

type graphmlEdge struct {
	ID     string        `xml:"id,attr"`
	Source string        `xml:"source,attr"`
	Target string        `xml:"target,attr"`
	Data   []graphmlData `xml:"data"`
}

type graphmlData struct {
	Key   string `xml:"key,attr"`
	Value string `xml:",chardata"`
}

// graphmlValues accumulates the <data> children of one element, dropping
// absent values.
type graphmlValues []graphmlData

func (d *graphmlValues) str(key, v string) {
	if v != "" {
		*d = append(*d, graphmlData{Key: key, Value: v})
	}
}

func (d *graphmlValues) num(key string, v int) {
	if v != 0 {
		*d = append(*d, graphmlData{Key: key, Value: strconv.Itoa(v)})
	}
}

// exact emits a number that is meaningful at zero (a community id).
func (d *graphmlValues) exact(key string, v int) {
	*d = append(*d, graphmlData{Key: key, Value: strconv.Itoa(v)})
}

func (d *graphmlValues) yes(key string, v bool) {
	if v {
		*d = append(*d, graphmlData{Key: key, Value: "true"})
	}
}

// WriteGraphML writes the snapshot as a GraphML document.
//
// The output carries no timestamp, so an unchanged graph exports byte for byte
// identically and the file can be committed and diffed.
func WriteGraphML(w io.Writer, g *Graph, generator string) error {
	st := g.Stats()
	desc := fmt.Sprintf("graphy code graph of %s: %d nodes, %d edges, %d communities, %d files",
		g.Root, st.Nodes, st.Edges, st.Communities, st.Files)
	if generator != "" {
		desc += " (generated by " + generator + ")"
	}
	doc := graphmlDocument{
		NS:             graphmlNS,
		XSI:            graphmlXSI,
		SchemaLocation: graphmlSchema,
		Desc:           desc,
		Keys:           graphmlKeys,
		Graph:          graphmlGraph{ID: "graphy", EdgeDefault: "directed"},
	}

	for _, n := range g.Nodes {
		var d graphmlValues
		d.str("label", n.Label)
		d.str("kind", string(n.Kind))
		d.str("language", n.Language)
		d.str("source_file", n.File)
		d.num("start_line", n.Span.StartLine)
		d.num("end_line", n.Span.EndLine)
		d.str("signature", n.Signature)
		d.str("doc", n.Doc)
		d.str("body", n.Body)
		if id, label, ok := g.Community(n.ID); ok {
			d.exact("community", id)
			d.str("community_label", label)
		}
		d.num("degree", n.Degree)
		d.yes("external", n.External)
		doc.Graph.Nodes = append(doc.Graph.Nodes, graphmlNode{ID: n.ID, Data: d})
	}

	for i, e := range g.Edges {
		var d graphmlValues
		d.str("relation", string(e.Relation))
		d.str("confidence", string(e.Confidence))
		d.str("site_file", e.File)
		d.num("site_line", e.Line)
		doc.Graph.Edges = append(doc.Graph.Edges, graphmlEdge{
			// Parallel edges are legal here (two calls to the same target from
			// different lines), so each gets an id readers can key on.
			ID: "e" + strconv.Itoa(i), Source: e.Source, Target: e.Target, Data: d,
		})
	}

	if _, err := io.WriteString(w, xml.Header); err != nil {
		return err
	}
	enc := xml.NewEncoder(w)
	enc.Indent("", "  ")
	if err := enc.Encode(doc); err != nil {
		return err
	}
	_, err := io.WriteString(w, "\n")
	return err
}
